import { build } from 'esbuild';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

// Resolve the vendor CSS imports at build time: the plugin cannot fetch npm
// package paths from a host page. Mantine's BlockNote sheet excludes global resets.
const result = await build({
  absWorkingDir: fileURLToPath(new URL('../', import.meta.url)),
  entryPoints: ['@blocknote/mantine/style.css'],
  bundle: true, write: false, minify: true, conditions: ['style'],
});
await writeFile(new URL('../packages/report-review/src/block-editor-styles.mjs', import.meta.url),
  '// Generated by scripts/build-editor-styles.mjs. Vendor licenses: THIRD_PARTY_NOTICES.md.\nexport default ' + JSON.stringify(result.outputFiles[0].text) + ';\n');
