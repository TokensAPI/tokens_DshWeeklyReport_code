import { build } from 'esbuild';
import { readFile, readdir, writeFile, copyFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { clientExternals } from './client-externals.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const result = await build({ absWorkingDir: root, entryPoints: ['packages/report-review/src/entry.jsx'], bundle: true,
  write: false, metafile: true, format: 'cjs', platform: 'browser', jsx: 'automatic',
  external: clientExternals, loader: { '.css': 'text' } });
const packages = new Map();
for (const input of Object.keys(result.metafile.inputs)) {
  if (!input.includes('node_modules/')) continue;
  let folder = dirname(join(root, input));
  while (folder !== root) {
    try {
      const pkg = JSON.parse(await readFile(join(folder, 'package.json'), 'utf8'));
      if (pkg.name) { packages.set(pkg.name, { ...pkg, folder }); break; }
    } catch { /* ascend to owning package */ }
    const parent = dirname(folder); if (parent === folder) break; folder = parent;
  }
}
const rows = [], missing = [];
const supplementalLicenses = {
  'react-remove-scroll-bar': 'https://github.com/theKashey/react-remove-scroll-bar/blob/8ca9ba5ea52de03308fe8ced94f7b159a44d28ff/LICENSE',
};
for (const pkg of [...packages.values()].sort((a, b) => a.name.localeCompare(b.name))) {
  const license = (await readdir(pkg.folder)).find(file => /^licen[sc]e(?:\.|$)/i.test(file));
  const name = pkg.name.replace(/^@/, '').replaceAll('/', '--');
  if (license) await copyFile(join(pkg.folder, license), join(root, 'third_party/licenses', name + '.LICENSE'));
  else if (supplementalLicenses[pkg.name]) {
    await readFile(join(root, 'third_party/licenses', name + '.LICENSE'), 'utf8');
  } else {
    missing.push(pkg.name);
    await writeFile(join(root, 'third_party/licenses', name + '.NOTICE'),
      `The npm package ${pkg.name}@${pkg.version} declares ${pkg.license} but ships no standalone license file. Package metadata and upstream README are retained below.\n\n` +
      await readFile(join(pkg.folder, 'package.json'), 'utf8') + '\n\n' + await readFile(join(pkg.folder, 'README.md'), 'utf8') + '\n\n' +
      (pkg.license === 'MIT' ? `Standard MIT permission text accompanying the upstream MIT declaration (the upstream package supplies no separate copyright notice):

Permission is hereby granted, free of charge, to any person obtaining a copy
of this software and associated documentation files (the "Software"), to deal
in the Software without restriction, including without limitation the rights
to use, copy, modify, merge, publish, distribute, sublicense, and/or sell
copies of the Software, and to permit persons to whom the Software is
furnished to do so, subject to the following conditions:

The above copyright notice and this permission notice shall be included in
all copies or substantial portions of the Software.

THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR
IMPLIED, INCLUDING BUT NOT LIMITED TO THE WARRANTIES OF MERCHANTABILITY,
FITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT. IN NO EVENT SHALL THE
AUTHORS OR COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER
LIABILITY, WHETHER IN AN ACTION OF CONTRACT, TORT OR OTHERWISE, ARISING FROM,
OUT OF OR IN CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS IN
THE SOFTWARE.
` : ''));
  }
  rows.push(`| \`${pkg.name}\` | ${pkg.version} | ${pkg.license} |`);
}
await writeFile(join(root, 'THIRD_PARTY_NOTICES.md'), `# Bundled browser dependencies

Generated by \`node scripts/update-client-notices.mjs\` from the client esbuild inputs. Available verbatim license files are retained under \`third_party/licenses/\`.

| Package | Version | License |
| --- | --- | --- |
${rows.join('\n')}

React, \`react/jsx-runtime\`, \`react-dom\`, \`react-dom/client\`, and \`@deepseek-ai/dsh-client-ui-primitives\` are supplied by the DSH Web shell. The compatibility tests use React/React DOM 18.3.1, matching the installed DSH runtime, with Mantine 8.3.18.

Packages without an available standalone license file: ${missing.join(', ') || 'none'}. Their upstream package metadata, README and standard MIT permission text are preserved as .NOTICE files; no upstream copyright attribution has been invented.

Supplemental upstream license: react-remove-scroll-bar — ${supplementalLicenses['react-remove-scroll-bar']}.

BlockNote Core, React and Mantine 0.54.2 are used under MPL-2.0 without vendor-source modifications. Their corresponding source is available at https://github.com/TypeCellOS/BlockNote/tree/v0.54.2 and in the versioned npm source packages https://registry.npmjs.org/@blocknote/core/-/core-0.54.2.tgz, https://registry.npmjs.org/@blocknote/react/-/react-0.54.2.tgz and https://registry.npmjs.org/@blocknote/mantine/-/mantine-0.54.2.tgz. The MPL license and source rights remain applicable to those files; this plugin does not limit those rights. No BlockNote XL packages are included. PDF generation continues to use report-pdf.
`);
console.log(`Updated notices for ${rows.length} bundled packages`);
